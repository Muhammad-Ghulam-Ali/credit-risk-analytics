-- 2. BUREAU
CREATE TABLE bureau (
    SK_ID_BUREAU INT PRIMARY KEY,
    SK_ID_CURR INT,
    CREDIT_ACTIVE VARCHAR(10),
    CREDIT_CURRENCY VARCHAR(12),
    DAYS_CREDIT INT,
    CREDIT_DAY_OVERDUE INT,
    DAYS_CREDIT_ENDDATE INT,
    DAYS_ENDDATE_FACT INT,
    AMT_CREDIT_MAX_OVERDUE DECIMAL(14,2),
    CNT_CREDIT_PROLONG INT,
    AMT_CREDIT_SUM DECIMAL(14,2),
    AMT_CREDIT_SUM_DEBT DECIMAL(14,2),
    AMT_CREDIT_SUM_LIMIT DECIMAL(14,2),
    AMT_CREDIT_SUM_OVERDUE DECIMAL(14,2),
    CREDIT_TYPE VARCHAR(50),
    DAYS_CREDIT_UPDATE INT,
    AMT_ANNUITY DECIMAL(12,2),
    FOREIGN KEY (SK_ID_CURR) REFERENCES application(SK_ID_CURR)
);

-- 3. PREVIOUS_APPLICATION
CREATE TABLE previous_application (
    SK_ID_PREV INT PRIMARY KEY,
    SK_ID_CURR INT,
    NAME_CONTRACT_TYPE VARCHAR(20),
    AMT_ANNUITY DECIMAL(12,2),
    AMT_APPLICATION DECIMAL(14,2),
    AMT_CREDIT DECIMAL(14,2),
    AMT_DOWN_PAYMENT DECIMAL(12,2),
    AMT_GOODS_PRICE DECIMAL(14,2),
    WEEKDAY_APPR_PROCESS_START VARCHAR(10),
    HOUR_APPR_PROCESS_START INT,
    FLAG_LAST_APPL_PER_CONTRACT VARCHAR(3),
    NFLAG_LAST_APPL_IN_DAY TINYINT,
    RATE_DOWN_PAYMENT DECIMAL(8,6),
    RATE_INTEREST_PRIMARY DECIMAL(8,6),
    RATE_INTEREST_PRIVILEGED DECIMAL(8,6),
    NAME_CASH_LOAN_PURPOSE VARCHAR(35),
    NAME_CONTRACT_STATUS VARCHAR(15),
    DAYS_DECISION INT,
    NAME_PAYMENT_TYPE VARCHAR(45),
    CODE_REJECT_REASON VARCHAR(10),
    NAME_TYPE_SUITE VARCHAR(20),
    NAME_CLIENT_TYPE VARCHAR(12),
    NAME_GOODS_CATEGORY VARCHAR(30),
    NAME_PORTFOLIO VARCHAR(10),
    NAME_PRODUCT_TYPE VARCHAR(10),
    CHANNEL_TYPE VARCHAR(30),
    SELLERPLACE_AREA INT,
    NAME_SELLER_INDUSTRY VARCHAR(25),
    CNT_PAYMENT INT,
    NAME_YIELD_GROUP VARCHAR(15),
    PRODUCT_COMBINATION VARCHAR(35),
    DAYS_FIRST_DRAWING INT,
    DAYS_FIRST_DUE INT,
    DAYS_LAST_DUE_1ST_VERSION INT,
    DAYS_LAST_DUE INT,
    DAYS_TERMINATION INT,
    NFLAG_INSURED_ON_APPROVAL TINYINT,
    FOREIGN KEY (SK_ID_CURR) REFERENCES application(SK_ID_CURR)
);

-- 4. BUREAU_BALANCE (child of bureau)
CREATE TABLE bureau_balance (
    SK_ID_BUREAU INT,
    MONTHS_BALANCE INT,
    STATUS VARCHAR(3),
    PRIMARY KEY (SK_ID_BUREAU, MONTHS_BALANCE),
    FOREIGN KEY (SK_ID_BUREAU) REFERENCES bureau(SK_ID_BUREAU)
);

-- 5. POS_CASH_BALANCE (child of previous_application)
CREATE TABLE pos_cash_balance (
    SK_ID_PREV INT,
    SK_ID_CURR INT,
    MONTHS_BALANCE INT,
    CNT_INSTALMENT INT,
    CNT_INSTALMENT_FUTURE INT,
    NAME_CONTRACT_STATUS VARCHAR(25),
    SK_DPD INT,
    SK_DPD_DEF INT,
    PRIMARY KEY (SK_ID_PREV, MONTHS_BALANCE),
    FOREIGN KEY (SK_ID_PREV) REFERENCES previous_application(SK_ID_PREV)
);

-- 6. CREDIT_CARD_BALANCE (child of previous_application)
CREATE TABLE credit_card_balance (
    SK_ID_PREV INT,
    SK_ID_CURR INT,
    MONTHS_BALANCE INT,
    AMT_BALANCE DECIMAL(14,2),
    AMT_CREDIT_LIMIT_ACTUAL DECIMAL(14,2),
    AMT_DRAWINGS_ATM_CURRENT DECIMAL(14,2),
    AMT_DRAWINGS_CURRENT DECIMAL(14,2),
    AMT_DRAWINGS_OTHER_CURRENT DECIMAL(14,2),
    AMT_DRAWINGS_POS_CURRENT DECIMAL(14,2),
    AMT_INST_MIN_REGULARITY DECIMAL(12,2),
    AMT_PAYMENT_CURRENT DECIMAL(14,2),
    AMT_PAYMENT_TOTAL_CURRENT DECIMAL(14,2),
    AMT_RECEIVABLE_PRINCIPAL DECIMAL(14,2),
    AMT_RECIVABLE DECIMAL(14,2),
    AMT_TOTAL_RECEIVABLE DECIMAL(14,2),
    CNT_DRAWINGS_ATM_CURRENT INT,
    CNT_DRAWINGS_CURRENT INT,
    CNT_DRAWINGS_OTHER_CURRENT INT,
    CNT_DRAWINGS_POS_CURRENT INT,
    CNT_INSTALMENT_MATURE_CUM INT,
    NAME_CONTRACT_STATUS VARCHAR(15),
    SK_DPD INT,
    SK_DPD_DEF INT,
    PRIMARY KEY (SK_ID_PREV, MONTHS_BALANCE),
    FOREIGN KEY (SK_ID_PREV) REFERENCES previous_application(SK_ID_PREV)
);

-- 7. INSTALLMENTS_PAYMENTS (child of previous_application, surrogate key)
CREATE TABLE installments_payments (
    id INT AUTO_INCREMENT PRIMARY KEY,
    SK_ID_PREV INT,
    SK_ID_CURR INT,
    NUM_INSTALMENT_VERSION INT,
    NUM_INSTALMENT_NUMBER INT,
    DAYS_INSTALMENT INT,
    DAYS_ENTRY_PAYMENT INT,
    AMT_INSTALMENT DECIMAL(12,2),
    AMT_PAYMENT DECIMAL(12,2),
    FOREIGN KEY (SK_ID_PREV) REFERENCES previous_application(SK_ID_PREV)
);